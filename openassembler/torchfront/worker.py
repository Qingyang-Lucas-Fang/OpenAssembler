"""Isolated CUDA capture/runtime worker; torch is imported only inside the worker.

The frontend delegates graph lowering to TorchInductor/Triton. It never labels
those cubins as generated by OpenAssembler's PTX backend.
"""
from __future__ import annotations

import argparse
import base64
import functools
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time
import traceback
import types

from .archive import pack, unpack
from .instrument import DECORATOR, ProjectFinder, transform

TORCH_VERSION = '2.7.1'


def runtime_info():
    import torch
    if torch.__version__.split('+')[0] != TORCH_VERSION:
        raise RuntimeError(f"PyTorch application bundles currently require torch=={TORCH_VERSION}; "
                           f"found {torch.__version__}. Use --build-backend modal for the pinned environment.")
    if not torch.cuda.is_available():
        raise RuntimeError("PyTorch application capture needs a CUDA GPU. On macOS use "
                           "--build-backend modal (after `pip install modal && modal setup`).")
    capability = list(torch.cuda.get_device_capability())
    return {'torch': torch.__version__, 'cuda': torch.version.cuda, 'python': sys.version.split()[0],
            'device': torch.cuda.get_device_name(), 'capability': capability}


def _save_state(state):
    import torch
    out = io.BytesIO()
    torch.save(state, out)
    return out.getvalue()


def compare_states(reference: bytes, actual: bytes, rtol: float, atol: float,
                   state_rtol: float, state_atol: float):
    import torch
    expected = torch.load(io.BytesIO(reference), map_location='cpu', weights_only=True)
    got = torch.load(io.BytesIO(actual), map_location='cpu', weights_only=True)
    if expected.keys() != got.keys():
        raise RuntimeError('verification failed: eager/compiled execution observed different model or optimizer states')
    checked = 0
    for key in expected:
        e, g = expected[key], got[key]
        if isinstance(e, torch.Tensor):
            tensor_rtol, tensor_atol = ((state_rtol, state_atol) if key.startswith(('parameters/', 'optimizer/'))
                                        else (rtol, atol))
            try:
                torch.testing.assert_close(g, e, rtol=tensor_rtol, atol=tensor_atol, equal_nan=False)
            except AssertionError as exc:
                raise RuntimeError(f'verification failed at {key}: {exc}') from None
            checked += 1
        elif g != e:
            raise RuntimeError(f'verification failed at {key}: {g!r} != {e!r}')
    if not checked:
        raise RuntimeError('verification observed no model tensors; no comparison was performed')
    return {'status': 'ok', 'tensors_checked': checked, 'rtol': rtol, 'atol': atol,
            'state_rtol': state_rtol, 'state_atol': state_atol,
            'scope': 'observed model outputs, final parameters, gradients and optimizer state'}


def execute_program(root: Path, config: dict, state_path: Path, *, compiled: bool, report_path: Path):
    """One fresh process per eager/compiled invocation gives both the same seed/import state."""
    import torch
    info = runtime_info()
    torch.set_num_threads(2)
    torch.manual_seed(config['seed'])
    torch.cuda.manual_seed_all(config['seed'])
    # Preserve eager RNG semantics for dropout when comparing with a compiled model.
    import torch._inductor.config as inductor_config
    inductor_config.fallback_random = True
    inductor_config.compile_threads = 1
    models, outputs, optimizers, graphs = {}, {}, [], []
    total_output_bytes = 0

    def snapshot(value, key, result):
        nonlocal total_output_bytes
        if isinstance(value, torch.Tensor):
            total_output_bytes += value.numel() * value.element_size()
            if total_output_bytes > 128 * 1024 * 1024:
                raise RuntimeError('verification tensor snapshots exceed 128 MiB; use a smaller capture workload')
            result[key] = value.detach().cpu().clone()
        elif isinstance(value, dict):
            for name, item in value.items():
                snapshot(item, f'{key}/{name}', result)
        elif isinstance(value, (tuple, list)):
            for index, item in enumerate(value):
                snapshot(item, f'{key}/{index}', result)
        elif isinstance(value, (str, bool, int, float)) or value is None:
            result[key] = value

    def compile_graph(graph, inputs):
        graphs.append({'nodes': len(list(graph.graph.nodes)), 'code': graph.code,
                       'operations': [str(n.target) for n in graph.graph.nodes if n.op == 'call_function']})
        from functorch.compile import make_boxed_func
        return make_boxed_func(torch._inductor.compile(graph, inputs))

    # Dynamo's ordinary custom backend captures the forward but leaves autograd
    # backward operations eager. This AOTAutograd bridge lowers both graphs.
    from torch._dynamo.backends.common import aot_autograd
    backend = aot_autograd(fw_compiler=compile_graph, bw_compiler=compile_graph)

    def decorate(forward):
        lowered = torch.compile(forward, backend=backend, dynamic=False, fullgraph=True) if compiled else forward
        @functools.wraps(forward)
        def wrapped(model, *args, **kwargs):
            if compiled and torch.compiler.is_compiling():
                return forward(model, *args, **kwargs)
            name = forward.__module__ + '.' + forward.__qualname__
            if name in models and models[name] is not model:
                name += f'#{len(models)}'
            models[name] = model
            value = lowered(model, *args, **kwargs)
            # This wrapper itself is eager. Only the original model method enters
            # Dynamo; reading/copying tensors here cannot introduce graph breaks.
            index = outputs.setdefault(name, 0)
            if index < 2:
                snapshot(value, f'outputs/{name}/{index}', observed)
            outputs[name] += 1
            return value
        return wrapped

    # Instrument optimizer state/step counts without changing optimizer semantics.
    original_init = torch.optim.Optimizer.__init__
    def optimizer_init(optimizer, *args, **kwargs):
        original_init(optimizer, *args, **kwargs)
        record = {'optimizer': optimizer, 'steps': 0}
        def after_step(*_args, **_kwargs):
            record['steps'] += 1
        optimizer.register_step_post_hook(after_step)
        optimizers.append(record)
    torch.optim.Optimizer.__init__ = optimizer_init

    new_codegen = []
    if config.get('mode') == 'run' and compiled:
        # Triton.compile itself runs on cache hits too. Prohibit the actual PTX ->
        # cubin stage so a missing shape/kernel cannot silently JIT during `run`.
        from triton.backends.nvidia.compiler import CUDABackend
        def forbidden_codegen(*_args, **_kwargs):
            new_codegen.append(True)
            raise RuntimeError('run needs an uncaptured CUDA specialization; recompile this application with its new arguments/shapes')
        CUDABackend.make_cubin = staticmethod(forbidden_codegen)

    observed = {}
    entry = root / config['entrypoint']
    sys.path[:0] = [str(entry.parent), str(root)]
    sys.argv = [str(entry), *config['args']]
    os.chdir(root)
    finder = ProjectFinder(root, decorate)
    sys.meta_path.insert(0, finder)
    main = types.ModuleType('__main__')
    main.__file__ = str(entry)
    main.__package__ = None
    main.__dict__[DECORATOR] = decorate
    sys.modules['__main__'] = main
    code, targets = transform(entry.read_text(), str(entry))
    t0 = time.monotonic()
    exec(code, main.__dict__)
    torch.cuda.synchronize()
    for name, model in models.items():
        snapshot(model.state_dict(), f'parameters/{name}', observed)
        for key, parameter in model.named_parameters():
            if parameter.grad is not None:
                snapshot(parameter.grad, f'gradients/{name}/{key}', observed)
    for index, record in enumerate(optimizers):
        observed[f'optimizer/{index}/steps'] = record['steps']
        snapshot(record['optimizer'].state_dict(), f'optimizer/{index}/state', observed)
    state_path.write_bytes(_save_state(observed))
    report = {'runtime': info, 'compiled': compiled, 'model_instances': len(models),
              'forward_calls': sum(outputs.values()), 'optimizer_steps': sum(r['steps'] for r in optimizers),
              'graphs': graphs, 'seconds': time.monotonic() - t0, 'new_gpu_codegen': len(new_codegen)}
    report_path.write_text(json.dumps(report, indent=1))


def _child(root, config, scratch, tag, compiled, budget):
    cp, sp, rp = scratch / (tag + '.json'), scratch / (tag + '.pt'), scratch / (tag + '.report.json')
    cp.write_text(json.dumps(config))
    cmd = [sys.executable, '-m', 'openassembler.torchfront.worker', '--execute', str(root),
           '--config', str(cp), '--state', str(sp), '--report', str(rp)]
    if compiled:
        cmd.append('--compiled')
    proc = subprocess.run(cmd, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=budget)
    print(proc.stdout, flush=True)
    if proc.returncode:
        raise RuntimeError(f'{tag} application failed (exit {proc.returncode}):\n{proc.stdout[-14000:]}')
    if not rp.is_file() or not sp.is_file():
        raise RuntimeError(f'{tag} application did not finish capture')
    return json.loads(rp.read_text()), sp.read_bytes()


def process(request: dict) -> dict:
    """Compile or replay a configured project, returning a bounded artifact archive."""
    info = runtime_info()
    config = request['config']
    if info['capability'] != [8, 0]:
        raise RuntimeError(f"this application targets sm_80; received GPU capability {info['capability']}")
    if request['mode'] == 'run':
        expected = request['runtime']
        for key in ('torch', 'cuda', 'python', 'capability'):
            if info[key] != expected[key]:
                raise RuntimeError(f'application runtime {key} differs from the build ({info[key]!r} != {expected[key]!r}); recompile')
    # Stable source/cache paths are important to Dynamo/Inductor cache keys.
    import fcntl
    workspace = Path(tempfile.gettempdir()) / ('openassembler-app-' + request['digest'])
    lock_path = workspace.with_suffix('.lock')
    with lock_path.open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if workspace.exists():
            shutil.rmtree(workspace)
        workspace.mkdir()
        try:
            unpack(base64.b64decode(request['source'], validate=True), workspace / 'source')
            if request['mode'] == 'run':
                unpack(base64.b64decode(request['cache'], validate=True), workspace / 'cache')
            root, cache = workspace / 'source', workspace / 'cache'
            os.environ.update(TORCHINDUCTOR_CACHE_DIR=str(cache / 'inductor'),
                              TRITON_CACHE_DIR=str(cache / 'triton'), TORCHINDUCTOR_FX_GRAPH_CACHE='1',
                              TORCHINDUCTOR_AUTOGRAD_CACHE='1', TORCHINDUCTOR_COMPILE_THREADS='1',
                              PYTHONHASHSEED='0', CUDA_MODULE_LOADING='LAZY')
            # Child module execution must still find the package after chdir.
            os.environ['PYTHONPATH'] = str(Path(__file__).resolve().parents[2]) + os.pathsep + os.environ.get('PYTHONPATH', '')
            start = time.monotonic()
            def remaining():
                seconds = request['budget'] - (time.monotonic() - start)
                if seconds < 1:
                    raise RuntimeError('application capture exceeded its total budget')
                return seconds
            requirements = request.get('requirements', config.get('requirements', []))
            if requirements:
                constraint = workspace / 'torch-constraint.txt'
                constraint.write_text('torch==2.7.1\n')
                for rel in requirements:
                    req_file = (root / rel).resolve()
                    if not req_file.is_relative_to(root.resolve()) or not req_file.is_file():
                        raise RuntimeError(f"configured requirements file is missing or escapes the source bundle: {rel}")
                    try:
                        installed = subprocess.run([sys.executable, '-m', 'pip', 'install', '--disable-pip-version-check',
                                                    '--no-input', '-c', str(constraint), '-r', str(req_file)],
                                                   cwd=root, text=True, stdout=subprocess.PIPE,
                                                   stderr=subprocess.STDOUT, timeout=remaining())
                    except subprocess.TimeoutExpired:
                        raise RuntimeError(f"dependency installation exceeded the remaining {request['budget']:g}s application budget") from None
                    print(installed.stdout, flush=True)
                    if installed.returncode:
                        raise RuntimeError(f"dependency installation failed for {rel}:\n{installed.stdout[-8000:]}")
                info = runtime_info()
                if info['capability'] != [8, 0]:
                    raise RuntimeError(f"dependency installation changed the runtime GPU; expected sm_80, got {info['capability']}")
                if request['mode'] == 'run':
                    expected = request['runtime']
                    for key in ('torch', 'cuda', 'python', 'capability'):
                        if info[key] != expected[key]:
                            raise RuntimeError(f"application runtime {key} differs from the build after dependency installation; recompile")
            cfg = {**config, 'mode': request['mode']}
            verification = {'status': 'not-run'}
            eager_state = None
            child_budget = lambda: min(remaining(), config.get('job_timeout', request['budget']))
            if request.get('verify'):
                _, eager_state = _child(root, cfg, workspace, 'eager', False, child_budget())
            result, state = _child(root, cfg, workspace, 'compiled', True, child_budget())
            if not result['model_instances'] or request['mode'] == 'compile' and not result['graphs']:
                raise RuntimeError('no project model forward graphs were captured; define a model with forward() or use the kernel frontend')
            if eager_state is not None:
                verification = compare_states(eager_state, state, config['rtol'], config['atol'],
                                              config['state_rtol'], config['state_atol'])
            if request['mode'] == 'run':
                return {'report': {**result, 'verification': verification, 'status': 'ok'}}
            artifacts, kernels = {}, []
            import hashlib
            for cub in sorted((cache / 'triton').rglob('*.cubin')):
                binary = cub.read_bytes()
                stem = cub.stem + '-' + hashlib.sha256(binary).hexdigest()[:12]
                rel = 'cubin/' + stem + '.cubin'
                if rel in artifacts:
                    continue
                artifacts[rel] = binary
                ptx = cub.with_suffix('.ptx')
                if ptx.is_file():
                    artifacts['ptx/' + stem + '.ptx'] = ptx.read_bytes()
                metadata_file = cub.with_suffix('.json')
                metadata = json.loads(metadata_file.read_text()) if metadata_file.exists() else {}
                listing = None
                if not request.get('no_sass'):
                    command = [shutil.which('nvdisasm') or '/usr/local/cuda/bin/nvdisasm', '-hex', '-c', str(cub)]
                    listing = subprocess.run(command, capture_output=True, text=True, timeout=remaining(), check=True).stdout
                    artifacts['sass/' + stem + '.sass'] = listing.encode()
                kernels.append({'name': metadata.get('name', cub.stem), 'artifact': stem,
                                'sha256': hashlib.sha256(binary).hexdigest(),
                                'cache_path': cub.relative_to(cache).as_posix(),
                                'compiled_by': 'torch-inductor-triton', 'metadata': metadata})
            if not kernels:
                raise RuntimeError('the application produced no Triton cubins; CUDA library-only graphs are not a compiled kernel bundle')
            cache_files = {p.relative_to(cache).as_posix(): p.read_bytes() for p in cache.rglob('*')
                           if p.is_file() and not p.is_symlink() and '.lock' not in p.name}
            artifacts['cache.zip'] = pack(cache_files)
            artifacts['graphs.json'] = json.dumps(result['graphs'], indent=1).encode()
            result.update(status='ok', verification=verification, kernels=kernels,
                          coverage={'compiled': 'project model forward graphs and autograd-generated backward kernels',
                                    'host_runtime': 'Python data/control flow and eager optimizer',
                                    'external_dependencies': ['PyTorch ATen CUDA kernels', 'cuBLAS', 'cuDNN'],
                                    'specialization': 'configured arguments and observed input shapes/branches'})
            return {'report': result, 'artifacts': base64.b64encode(pack(artifacts)).decode()}
        finally:
            shutil.rmtree(workspace, ignore_errors=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--request', type=Path)
    parser.add_argument('--result', type=Path)
    parser.add_argument('--execute', type=Path)
    parser.add_argument('--config', type=Path)
    parser.add_argument('--state', type=Path)
    parser.add_argument('--report', type=Path)
    parser.add_argument('--compiled', action='store_true')
    a = parser.parse_args()
    if a.execute:
        execute_program(a.execute, json.loads(a.config.read_text()), a.state, compiled=a.compiled, report_path=a.report)
    else:
        try:
            result = process(json.loads(a.request.read_text()))
        except Exception:
            result = {'error': traceback.format_exc()}
        a.result.write_text(json.dumps(result))
        return 1 if 'error' in result else 0
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
